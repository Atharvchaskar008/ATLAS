# 4. CONTINUOUS SPATIAL RESOLVER & INTERPOLATOR FOR ANY POINT IN MAHARASHTRA
# =============================================================================
def resolve_maharashtra_coordinates(lat: float, lng: float) -> Dict[str, Any]:
    """
    Given ANY arbitrary GPS point (lat, lng) in Maharashtra:
    1. Finds closest registered hubs.
    2. Performs Inverse Distance Weighting (IDW) to estimate Ready Reckoner (ASR) circle rate,
       market pricing bands, annual appreciation CAGR, and gross rental yield.
    3. Identifies official administrative authority and statutory stamp duty liability.
    """
    # Check if point is inside Maharashtra bounding box
    within_mh = is_in_maharashtra(lat, lng)

    # Compute distances to all master localities
    hub_distances = []
    for loc_name, loc_data in MAHARASHTRA_LOCALITIES_REGISTRY.items():
        dist = haversine_km(lat, lng, loc_data["lat"], loc_data["lng"])
        hub_distances.append((dist, loc_name, loc_data))

    hub_distances.sort(key=lambda x: x[0])
    nearest_dist, nearest_name, nearest_meta = hub_distances[0]

    # If within 4 km of a known registered hub, snap directly to it
    if nearest_dist <= 4.0:
        res = dict(nearest_meta)
        res["lat"] = lat
        res["lng"] = lng
        res["is_interpolated"] = False
        res["distance_to_anchor_km"] = round(nearest_dist, 2)
        res["anchor_name"] = nearest_name
        res["is_in_maharashtra"] = within_mh
        return res

    # Otherwise, perform spatial Inverse Distance Weighting across top 3 closest hubs
    top_3 = hub_distances[:3]
    weights = [1.0 / max(0.5, d[0] ** 1.6) for d in top_3]
    total_w = sum(weights)

    interp_asr_carpet = sum(w * d[2]["ready_reckoner_rate_carpet_sqft"] for w, d in zip(weights, top_3)) / total_w
    interp_asr_builtup = sum(w * d[2]["ready_reckoner_rate_builtup_sqft"] for w, d in zip(weights, top_3)) / total_w
    interp_mkt_avg = sum(w * d[2]["market_rate_carpet_sqft_avg"] for w, d in zip(weights, top_3)) / total_w
    interp_mkt_min = sum(w * d[2]["market_rate_carpet_sqft_min"] for w, d in zip(weights, top_3)) / total_w
    interp_mkt_max = sum(w * d[2]["market_rate_carpet_sqft_max"] for w, d in zip(weights, top_3)) / total_w
    interp_growth = sum(w * d[2]["growth_rate_annual_pct"] for w, d in zip(weights, top_3)) / total_w
    interp_rental = sum(w * d[2].get("rental_yield_pct", 3.6) for w, d in zip(weights, top_3)) / total_w

    # Statutory authority and stamp duty rate
    if nearest_dist < 20.0:
        authority = nearest_meta["authority"]
        stamp_duty = nearest_meta.get("stamp_duty_pct", 7.0)
    else:
        authority = f"Town Planning / Collector Office ({nearest_meta['district']})"
        stamp_duty = 6.0

    synthetic_name = f"{nearest_meta['name']} Outer Sector ({round(nearest_dist, 1)} km)" if nearest_dist > 5.0 else nearest_meta["name"]

    return {
        "id": f"INTERP-{nearest_meta['district'][:3].upper()}-{int(lat*100)}-{int(lng*100)}",
        "name": synthetic_name,
        "district": nearest_meta["district"],
        "taluka": nearest_meta.get("taluka", nearest_meta["district"]),
        "region": nearest_meta["region"],
        "authority": authority,
        "sub_localities": [f"Sector Coord ({lat:.4f}, {lng:.4f})", f"Near {nearest_meta['name']}"],
        "lat": lat,
        "lng": lng,
        "pincode": nearest_meta["pincode"],
        "ready_reckoner_rate_builtup_sqft": int(round(interp_asr_builtup)),
        "ready_reckoner_rate_carpet_sqft": int(round(interp_asr_carpet)),
        "market_rate_carpet_sqft_min": int(round(interp_mkt_min)),
        "market_rate_carpet_sqft_avg": int(round(interp_mkt_avg)),
        "market_rate_carpet_sqft_max": int(round(interp_mkt_max)),
        "growth_rate_annual_pct": round(interp_growth, 1),
        "rental_yield_pct": round(interp_rental, 1),
        "stamp_duty_pct": stamp_duty,
        "tier_class": f"{nearest_meta['district']} Micro-Zone",
        "infrastructure_notes": f"Spatial proximity to {nearest_meta['name']} ({round(nearest_dist, 1)} km); {nearest_meta['infrastructure_notes']}",
        "top_societies": [f"Residencies around {nearest_meta['name']}"],
        "is_interpolated": True,
        "anchor_name": nearest_meta["name"],
        "distance_to_anchor_km": round(nearest_dist, 2),
        "is_in_maharashtra": within_mh
    }
